"""Runs every Task 1 + Task 2 eval case through scorer.py and writes eval_report.json
+ eval_report.md at the repo root (PRD §4). This is cases_triage.CASES / cases_brief.CASES'
real caller.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from src.eval.cases_brief import CASES as BRIEF_CASES
from src.eval.cases_triage import CASES as TRIAGE_CASES
from src.eval.scorer import EvalResult, score_brief_case, score_triage_case

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
REPORT_JSON_PATH = REPO_ROOT / "eval_report.json"
REPORT_MD_PATH = REPO_ROOT / "eval_report.md"


def run_all() -> list[EvalResult]:
    """Score every triage case then every account-brief case, in definition order."""
    return [score_triage_case(c) for c in TRIAGE_CASES] + [score_brief_case(c) for c in BRIEF_CASES]


def _write_json_report(results: list[EvalResult]) -> None:
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "total_cases": len(results),
        "hard_gate_passes": sum(r.hard_gate_pass for r in results),
        "hard_gate_failures": sum(not r.hard_gate_pass for r in results),
        "results": [
            {
                "case_id": r.case_id,
                "task": r.task,
                "adversarial": r.adversarial,
                "hard_gate_pass": r.hard_gate_pass,
                "hard_gate_failures": r.hard_gate_failures,
                "quality_score": r.quality_score,
                "judge_notes": r.judge_notes,
                "notes": r.notes,
            }
            for r in results
        ],
    }
    REPORT_JSON_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def _write_md_report(results: list[EvalResult]) -> None:
    n_pass = sum(r.hard_gate_pass for r in results)
    lines = [
        "# Eval Report",
        "",
        "Generated by `python run.py eval` (src/eval/run_eval.py).",
        "",
        f"**{n_pass}/{len(results)} cases passed hard gates.**",
        "",
        "| case_id | task | adversarial | hard_gate_pass | quality_score | notes |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        score = f"{r.quality_score:.2f}" if r.quality_score is not None else "—"
        notes = r.notes.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {r.case_id} | {r.task} | {r.adversarial} | {'PASS' if r.hard_gate_pass else 'FAIL'} | {score} | {notes} |")
    REPORT_MD_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> list[EvalResult]:
    results = run_all()
    _write_json_report(results)
    _write_md_report(results)
    return results


if __name__ == "__main__":
    main()
